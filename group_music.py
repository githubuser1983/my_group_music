def _require_mido():
    try:
        import mido
        return mido
    except ImportError as exc:
        raise ImportError("Install mido with: pip install mido") from exc


def write_pitches(
    filename: str,
    voices_data: Sequence[Sequence[tuple[float, float, int, bool, float]]],
    tempo: float = 82,
    instrument: Sequence[int] | None = None,
    add21: bool = True,
    start_at: Sequence[float] | None = None,
    durations_in_quarter_notes: bool = False,
    ticks_per_beat: int = 480,
) -> str:
    """
    Write the legacy voice-event representation with mido.

    Event format:
        (pitch, duration, volume, is_pause, event_tempo)

    The old code multiplied duration by 4 when durationsInQuarterNotes=False;
    this compatibility behavior is preserved.
    """
    mido = _require_mido()
    ni = len(voices_data)
    if ni == 0:
        raise ValueError("voices_data is empty")
    if ni > 16:
        raise ValueError("standard MIDI supports at most 16 channels in this simple writer")

    instruments = list(instrument) if instrument is not None else [0] * ni
    starts = list(start_at) if start_at is not None else [0.0] * ni
    instruments += [0] * max(0, ni - len(instruments))
    starts += [0.0] * max(0, ni - len(starts))

    mid = mido.MidiFile(type=1, ticks_per_beat=int(ticks_per_beat))
    tempo_msg = mido.bpm2tempo(float(tempo))

    for k, voice in enumerate(voices_data):
        track = mido.MidiTrack()
        mid.tracks.append(track)
        channel = k
        events = []
        serial = 0

        events.append((0, 0, serial, mido.MetaMessage("set_tempo", tempo=tempo_msg, time=0)))
        serial += 1
        events.append((0, 1, serial, mido.Message("program_change", channel=channel, program=max(0, min(127, int(instruments[k]))), time=0)))
        serial += 1

        current_beats = float(starts[k])
        for event in voice:
            pitch, duration, volume, is_pause, _event_tempo = event
            duration_beats = float(duration) if durations_in_quarter_notes else 4.0 * float(duration)
            duration_beats = max(0.0, duration_beats)
            start_tick = int(round(current_beats * ticks_per_beat))
            end_tick = int(round((current_beats + duration_beats) * ticks_per_beat))

            if not is_pause and duration_beats > 0:
                p = floor(float(pitch)) + (21 if add21 else 0)
                p = max(0, min(127, int(p)))
                v = max(0, min(127, int(volume)))
                events.append((start_tick, 3, serial, mido.Message("note_on", channel=channel, note=p, velocity=v, time=0)))
                serial += 1
                events.append((max(start_tick + 1, end_tick), 2, serial, mido.Message("note_off", channel=channel, note=p, velocity=0, time=0)))
                serial += 1

            current_beats += duration_beats

        events.sort(key=lambda e: (e[0], e[1], e[2]))
        last_tick = 0
        for tick, _priority, _serial, msg in events:
            track.append(msg.copy(time=max(0, tick - last_tick)))
            last_tick = tick
        track.append(mido.MetaMessage("end_of_track", time=0))

    mid.save(filename)
    print("written:", filename)
    return filename


