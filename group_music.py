def parse_group(spec: str) -> FiniteGroup:
    """
    Parse useful short names:
      D4, C8, S4, A4, V4/K4, Q8, abelian:2,9,5
    """
    s = spec.strip().upper()
    if s in ("V4", "K4", "KLEIN"):
        return KleinFourGroup()
    if s in ("Q8", "QUATERNION"):
        return QuaternionGroup()
    if s.startswith("ABELIAN:"):
        mods = [int(x.strip()) for x in spec.split(":", 1)[1].split(",") if x.strip()]
        return AbelianGroup(mods)
    if len(s) >= 2 and s[0] in "CDSA" and s[1:].isdigit():
        n = int(s[1:])
        if s[0] == "C":
            return CyclicPermutationGroup(n)
        if s[0] == "D":
            return DihedralGroup(n)
        if s[0] == "S":
            return SymmetricGroup(n)
        if s[0] == "A":
            return AlternatingGroup(n)
    raise ValueError(f"Unknown group specification: {spec!r}")


