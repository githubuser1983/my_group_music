def _decimal_parity_bits(value: str | float | int | Any, digits: int) -> list[int]:
    """Convert decimal digits of a constant to parity bits digit mod 2."""
    try:
        import mpmath as mp
    except ImportError as exc:
        raise ImportError("Install mpmath with: pip install mpmath") from exc

    digits = max(20, int(digits))
    old_dps = mp.mp.dps
    mp.mp.dps = digits + 10
    try:
        if value is None or value == "pi":
            x = mp.pi
        elif value == "exp(-pi)":
            x = mp.exp(-mp.pi)
        elif callable(value):
            x = value(mp)
        else:
            x = mp.mpf(value)
        s = mp.nstr(x, n=digits + 2, strip_zeros=False)
    finally:
        mp.mp.dps = old_dps

    # mpmath may use scientific notation for very small/large constants.
    if "e" in s.lower():
        old_dps = mp.mp.dps
        mp.mp.dps = digits + 10
        try:
            if value is None or value == "pi":
                x = mp.pi
            elif value == "exp(-pi)":
                x = mp.exp(-mp.pi)
            elif callable(value):
                x = value(mp)
            else:
                x = mp.mpf(value)
            s = mp.nstr(x, n=digits + 2, min_fixed=-1000000, max_fixed=1000000, strip_zeros=False)
        finally:
            mp.mp.dps = old_dps

    digits_only = [ch for ch in s if ch.isdigit()]
    # Match the Sage intention: use digits after the decimal point when possible.
    if "." in s:
        frac = s.split(".", 1)[1]
        if "e" in frac.lower():
            frac = frac.lower().split("e", 1)[0]
        digits_only = [ch for ch in frac if ch.isdigit()]
    if not digits_only:
        raise ValueError("could not extract decimal digits")
    return [int(ch) % 2 for ch in digits_only]


def group_music(
    G: FiniteGroup,
    chords: Sequence[Sequence[int]],
    tempo: float = 81,
    base_duration: float = 1 / 9,
    octave_range: tuple[int, int] = (-2, 2),
    pi_nr: Any = "pi",
    pi_digits: int = 10000,
    voices: int = 4,
    chord_change_every: int = 4,
    iter_it: int = 1,
):
    """
    Pure-Python port of the original Sage group_music().

    It deliberately preserves the original iter_it behavior for compatibility:
    for iter_it > 1 the element list is expanded by concatenating regular-action
    rows.  This is musically useful but is not a higher group power.
    """
    original_elts = list(G)
    n = len(original_elts)
    if n == 0:
        raise ValueError("G must be finite and non-empty")
    if not chords:
        raise ValueError("chords must not be empty")
    if voices <= 0:
        raise ValueError("voices must be positive")
    if chord_change_every <= 0:
        raise ValueError("chord_change_every must be positive")

    elts = list(original_elts)
    if iter_it > 1:
        expanded = []
        for _ in range(iter_it - 1):
            for g in elts:
                expanded.extend(g * h for h in elts)
        elts = expanded

    idx = {g: i for i, g in enumerate(elts)}
    bits = _decimal_parity_bits(pi_nr, pi_digits)

    lines = [[] for _ in range(voices)]
    octaves = [-2 + (v % 5) for v in range(voices)]
    signs = [1] * voices
    durations = [base_duration / (1 + (v % 4)) for v in range(voices)]

    lastbit = 0
    c = 0

    for g in elts:
        orbit = [g * h for h in elts]
        chord = chords[(c // chord_change_every) % len(chords)]
        m = len(chord)
        if m == 0:
            raise ValueError("chords may not contain empty chords")
        bit = bits[c % len(bits)]

        for j, h in enumerate(orbit):
            element_index = idx[h]

            for v in range(voices):
                if v % 4 == 0:
                    degree = (element_index + v) % m
                elif v % 4 == 1:
                    degree = (-element_index - 1 + v) % m
                elif v % 4 == 2:
                    degree = (2 * element_index + v) % m
                else:
                    degree = (element_index * element_index + v) % m

                pitch = int(chord[degree]) + 12 * octaves[v]
                while pitch < 0:
                    pitch += 12
                while pitch > 127:
                    pitch -= 12

                if v % 2 == 0:
                    volume = 90 - int(50 * j / max(1, n - 1))
                else:
                    volume = 45 + int(50 * j / max(1, n - 1))
                volume -= 4 * (v // 2)
                volume = max(1, min(127, volume))

                lines[v].append((pitch, float(durations[v]), int(volume), False, tempo))

        for v in range(voices):
            if octaves[v] <= octave_range[0]:
                signs[v] = 1
            if octaves[v] >= octave_range[1]:
                signs[v] = -1

            if v % 3 == 0:
                trigger = bit == 0
            elif v % 3 == 1:
                trigger = bit == 1
            else:
                trigger = lastbit != bit

            if trigger:
                octaves[v] = min(max(octaves[v] + signs[v], octave_range[0]), octave_range[1])

        if bit == 1 and voices > 1:
            durations = durations[1:] + durations[:1]

        lastbit = bit
        c += 1

    return lines


