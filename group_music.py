"""
group_music.py

Pure-Python port of the SageMath group-music experiment.

Dependencies:
    pip install mido mpmath

No SageMath, MIDIUtil, or local MidiFile.py is required.

The module contains:
  * a small finite-group / permutation toolkit,
  * constructors for common finite groups,
  * the original group_music() idea,
  * a mido-based MIDI writer.

Permutation convention
----------------------
A Permutation stores a 0-based vector p with p[i] = image of i.
Multiplication is function composition:

    (p * q)(i) = p(q(i)).

For a finite group G, regular_action_permutations() returns the permutations
x -> g*x (or x -> x*g) on the ordered set of elements of G.
"""

