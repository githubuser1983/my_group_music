@dataclass(frozen=True)
class Permutation:
    """Finite 0-based permutation."""

    images: tuple[int, ...]

    def __init__(self, images: Sequence[int]):
        images = tuple(int(x) for x in images)
        if sorted(images) != list(range(len(images))):
            raise ValueError(f"Not a permutation: {images}")
        object.__setattr__(self, "images", images)

    @property
    def degree(self) -> int:
        return len(self.images)

    def __call__(self, i: int) -> int:
        return self.images[i]

    def __mul__(self, other: "Permutation") -> "Permutation":
        """Composition self ∘ other."""
        if not isinstance(other, Permutation) or self.degree != other.degree:
            return NotImplemented
        return Permutation([self.images[other.images[i]] for i in range(self.degree)])

    def inverse(self) -> "Permutation":
        inv = [0] * self.degree
        for i, j in enumerate(self.images):
            inv[j] = i
        return Permutation(inv)

    def is_identity(self) -> bool:
        return self.images == tuple(range(self.degree))

    def cycles(self, include_fixed: bool = False) -> list[tuple[int, ...]]:
        seen = [False] * self.degree
        out: list[tuple[int, ...]] = []
        for i in range(self.degree):
            if seen[i]:
                continue
            cyc = []
            j = i
            while not seen[j]:
                seen[j] = True
                cyc.append(j)
                j = self.images[j]
            if include_fixed or len(cyc) > 1:
                out.append(tuple(cyc))
        return out

    def __repr__(self) -> str:
        cycles = self.cycles()
        if not cycles:
            return "()"
        return "".join("(" + " ".join(str(x + 1) for x in c) + ")" for c in cycles)


class FiniteGroup:
    """Minimal protocol used by the music algorithms."""

    def __iter__(self) -> Iterator[Any]:
        raise NotImplementedError

    def elements(self) -> list[Any]:
        return list(iter(self))

    def order(self) -> int:
        return len(self.elements())

    def identity(self) -> Any:
        raise NotImplementedError

    def generators(self) -> list[Any]:
        return []

    def degree(self) -> int:
        raise TypeError("This group has no distinguished natural permutation degree.")


class PermutationGroup(FiniteGroup):
    """Finite permutation group generated by explicit permutations."""

    def __init__(self, generators: Sequence[Permutation], degree: int | None = None):
        gens = list(generators)
        if degree is None:
            if not gens:
                raise ValueError("degree is required for a trivial permutation group")
            degree = gens[0].degree
        self._degree = int(degree)
        if self._degree <= 0:
            raise ValueError("degree must be positive")
        for g in gens:
            if g.degree != self._degree:
                raise ValueError("all generators must have the same degree")
        self._gens = gens[:] if gens else [Permutation(range(self._degree))]
        self._elements = self._closure(self._gens)

    def _closure(self, gens: Sequence[Permutation]) -> list[Permutation]:
        e = Permutation(range(self._degree))
        seen = {e}
        ordered = [e]
        q = deque([e])
        # Including inverses makes closure generation much faster for some groups.
        steps = list(gens)
        for g in gens:
            gi = g.inverse()
            if gi not in steps:
                steps.append(gi)
        while q:
            a = q.popleft()
            for g in steps:
                for b in (g * a, a * g):
                    if b not in seen:
                        seen.add(b)
                        ordered.append(b)
                        q.append(b)
        return ordered

    def __iter__(self) -> Iterator[Permutation]:
        return iter(self._elements)

    def order(self) -> int:
        return len(self._elements)

    def identity(self) -> Permutation:
        return Permutation(range(self._degree))

    def generators(self) -> list[Permutation]:
        return list(self._gens)

    def degree(self) -> int:
        return self._degree

    def __repr__(self) -> str:
        return f"PermutationGroup(order={self.order()}, degree={self.degree()})"


@dataclass(frozen=True)
class AbelianElement:
    moduli: tuple[int, ...]
    coords: tuple[int, ...]

    def __mul__(self, other: "AbelianElement") -> "AbelianElement":
        if not isinstance(other, AbelianElement) or self.moduli != other.moduli:
            return NotImplemented
        return AbelianElement(
            self.moduli,
            tuple((a + b) % m for a, b, m in zip(self.coords, other.coords, self.moduli)),
        )

    def __repr__(self) -> str:
        return str(self.coords)


class AbelianGroup(FiniteGroup):
    """Direct product C_n1 x ... x C_nk, written multiplicatively in the API."""

    def __init__(self, moduli: Sequence[int]):
        self.moduli = tuple(int(m) for m in moduli)
        if not self.moduli or any(m <= 0 for m in self.moduli):
            raise ValueError("moduli must be positive integers")
        self._elements = [
            AbelianElement(self.moduli, tuple(c))
            for c in product(*(range(m) for m in self.moduli))
        ]

    def __iter__(self) -> Iterator[AbelianElement]:
        return iter(self._elements)

    def identity(self) -> AbelianElement:
        return AbelianElement(self.moduli, (0,) * len(self.moduli))

    def generators(self) -> list[AbelianElement]:
        out = []
        for i, m in enumerate(self.moduli):
            if m == 1:
                continue
            c = [0] * len(self.moduli)
            c[i] = 1
            out.append(AbelianElement(self.moduli, tuple(c)))
        return out

    def order(self) -> int:
        n = 1
        for m in self.moduli:
            n *= m
        return n

    def __repr__(self) -> str:
        return "AbelianGroup(" + " x ".join(f"C{m}" for m in self.moduli) + ")"


@dataclass(frozen=True)
class DihedralElement:
    """r^k s^flip in D_n, with s r s = r^-1."""

    n: int
    k: int
    flip: int

    def __mul__(self, other: "DihedralElement") -> "DihedralElement":
        if not isinstance(other, DihedralElement) or self.n != other.n:
            return NotImplemented
        # (r^a s^b)(r^c s^d) = r^(a + (-1)^b c) s^(b+d)
        k = (self.k + (-1 if self.flip else 1) * other.k) % self.n
        return DihedralElement(self.n, k, (self.flip + other.flip) % 2)

    def as_permutation(self) -> Permutation:
        # natural action on vertices Z/nZ: r^k s^b : x -> k + (-1)^b x
        if self.flip:
            return Permutation([(self.k - x) % self.n for x in range(self.n)])
        return Permutation([(self.k + x) % self.n for x in range(self.n)])

    def __repr__(self) -> str:
        if self.flip:
            return f"r^{self.k}s"
        return f"r^{self.k}"


class DihedralGroup(FiniteGroup):
    """Symmetry group D_n of a regular n-gon, order 2n."""

    def __init__(self, n: int):
        self.n = int(n)
        if self.n < 2:
            raise ValueError("n must be >= 2")
        self._elements = [DihedralElement(self.n, k, b) for b in (0, 1) for k in range(self.n)]
        # put identity first explicitly
        self._elements.sort(key=lambda x: (x.flip != 0, x.k))

    def __iter__(self) -> Iterator[DihedralElement]:
        return iter(self._elements)

    def identity(self) -> DihedralElement:
        return DihedralElement(self.n, 0, 0)

    def generators(self) -> list[DihedralElement]:
        return [DihedralElement(self.n, 1, 0), DihedralElement(self.n, 0, 1)]

    def order(self) -> int:
        return 2 * self.n

    def degree(self) -> int:
        return self.n

    def natural_permutations(self) -> list[Permutation]:
        return [g.as_permutation() for g in self._elements]

    def __repr__(self) -> str:
        return f"DihedralGroup({self.n})"


