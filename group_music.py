_Q_UNITS = ("1", "i", "j", "k")
_Q_BASE_MUL = {
    ("1", "1"): (1, "1"), ("1", "i"): (1, "i"), ("1", "j"): (1, "j"), ("1", "k"): (1, "k"),
    ("i", "1"): (1, "i"), ("j", "1"): (1, "j"), ("k", "1"): (1, "k"),
    ("i", "i"): (-1, "1"), ("j", "j"): (-1, "1"), ("k", "k"): (-1, "1"),
    ("i", "j"): (1, "k"), ("j", "k"): (1, "i"), ("k", "i"): (1, "j"),
    ("j", "i"): (-1, "k"), ("k", "j"): (-1, "i"), ("i", "k"): (-1, "j"),
}


@dataclass(frozen=True)
class QuaternionElement:
    sign: int
    unit: str

    def __post_init__(self):
        if self.sign not in (-1, 1) or self.unit not in _Q_UNITS:
            raise ValueError("invalid quaternion unit")

    def __mul__(self, other: "QuaternionElement") -> "QuaternionElement":
        if not isinstance(other, QuaternionElement):
            return NotImplemented
        s, u = _Q_BASE_MUL[(self.unit, other.unit)]
        return QuaternionElement(self.sign * other.sign * s, u)

    def __repr__(self) -> str:
        return ("-" if self.sign < 0 else "") + self.unit


class QuaternionGroup(FiniteGroup):
    def __init__(self):
        self._elements = [QuaternionElement(1, "1"), QuaternionElement(-1, "1")]
        for u in ("i", "j", "k"):
            self._elements.extend([QuaternionElement(1, u), QuaternionElement(-1, u)])

    def __iter__(self) -> Iterator[QuaternionElement]:
        return iter(self._elements)

    def identity(self) -> QuaternionElement:
        return QuaternionElement(1, "1")

    def generators(self) -> list[QuaternionElement]:
        return [QuaternionElement(1, "i"), QuaternionElement(1, "j")]

    def order(self) -> int:
        return 8

    def __repr__(self) -> str:
        return "QuaternionGroup(Q8)"


@dataclass(frozen=True)
class DirectProductElement:
    components: tuple[Any, ...]

    def __mul__(self, other: "DirectProductElement") -> "DirectProductElement":
        if not isinstance(other, DirectProductElement) or len(self.components) != len(other.components):
            return NotImplemented
        return DirectProductElement(tuple(a * b for a, b in zip(self.components, other.components)))


class DirectProductGroup(FiniteGroup):
    def __init__(self, groups: Sequence[FiniteGroup]):
        self.groups = tuple(groups)
        if not self.groups:
            raise ValueError("at least one factor is required")
        self._factor_elements = [list(g) for g in self.groups]
        self._elements = [DirectProductElement(tuple(x)) for x in product(*self._factor_elements)]

    def __iter__(self) -> Iterator[DirectProductElement]:
        return iter(self._elements)

    def identity(self) -> DirectProductElement:
        return DirectProductElement(tuple(g.identity() for g in self.groups))

    def generators(self) -> list[DirectProductElement]:
        ids = [g.identity() for g in self.groups]
        out = []
        for i, g in enumerate(self.groups):
            for gen in g.generators():
                c = list(ids)
                c[i] = gen
                out.append(DirectProductElement(tuple(c)))
        return out

    def order(self) -> int:
        n = 1
        for g in self.groups:
            n *= g.order()
        return n


# Common permutation groups ----------------------------------------------------


def CyclicPermutationGroup(n: int) -> PermutationGroup:
    n = int(n)
    if n < 1:
        raise ValueError("n must be positive")
    rotation = Permutation([(i + 1) % n for i in range(n)])
    return PermutationGroup([rotation], degree=n)


def SymmetricGroup(n: int) -> PermutationGroup:
    n = int(n)
    if n < 1:
        raise ValueError("n must be positive")
    if n == 1:
        return PermutationGroup([], degree=1)
    cycle = Permutation([(i + 1) % n for i in range(n)])
    trans = list(range(n))
    trans[0], trans[1] = trans[1], trans[0]
    return PermutationGroup([cycle, Permutation(trans)], degree=n)


def AlternatingGroup(n: int) -> PermutationGroup:
    n = int(n)
    if n < 2:
        return PermutationGroup([], degree=max(1, n))
    if n == 2:
        return PermutationGroup([], degree=2)
    gens = []
    # A_n is generated by 3-cycles (0,1,k), k=2,...,n-1.
    for k in range(2, n):
        p = list(range(n))
        p[0], p[1], p[k] = 1, k, 0
        gens.append(Permutation(p))
    return PermutationGroup(gens, degree=n)


def KleinFourGroup() -> PermutationGroup:
    a = Permutation([1, 0, 3, 2])  # (1 2)(3 4)
    b = Permutation([2, 3, 0, 1])  # (1 3)(2 4)
    return PermutationGroup([a, b], degree=4)


def dihedral_permutation_group(n: int) -> PermutationGroup:
    """Natural permutation representation of D_n on n vertices."""
    D = DihedralGroup(n)
    gens = [g.as_permutation() for g in D.generators()]
    return PermutationGroup(gens, degree=n)


def DirectProduct(*groups: FiniteGroup) -> DirectProductGroup:
    return DirectProductGroup(groups)


