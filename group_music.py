def _ordered_group_elements(G: FiniteGroup, identity_first: bool = True) -> list[Any]:
    elts = list(G)
    if not identity_first or len(elts) <= 1:
        return elts
    try:
        e = G.identity()
    except Exception:
        return elts
    for i, g in enumerate(elts):
        if g == e:
            if i:
                elts = [g] + elts[:i] + elts[i + 1 :]
            break
    return elts


def regular_action_permutations(
    G: FiniteGroup,
    side: str = "left",
    identity_first: bool = True,
) -> dict[str, Any]:
    """Return all permutations of the left or right regular action of G."""
    if side not in ("left", "right"):
        raise ValueError("side must be 'left' or 'right'")
    elts = _ordered_group_elements(G, identity_first=identity_first)
    if not elts:
        raise ValueError("empty group")
    index = {g: i for i, g in enumerate(elts)}
    if len(index) != len(elts):
        raise ValueError("group elements must be hashable and distinct")

    perms = []
    for g in elts:
        images = []
        for x in elts:
            y = g * x if side == "left" else x * g
            if y not in index:
                raise ValueError(f"group multiplication left the enumerated group: {y!r}")
            images.append(index[y])
        perms.append(Permutation(images))

    return {
        "elements": elts,
        "permutations": perms,
        "degree": len(elts),
        "representation": "regular",
        "side": side,
    }


def given_action_permutations(G: FiniteGroup, identity_first: bool = True) -> dict[str, Any]:
    """Use the group's natural permutation action where available."""
    elts = _ordered_group_elements(G, identity_first=identity_first)

    if isinstance(G, PermutationGroup):
        perms = list(elts)
        d = G.degree()
    elif isinstance(G, DihedralGroup):
        perms = [g.as_permutation() for g in elts]
        d = G.degree()
    else:
        raise TypeError("given action is available for PermutationGroup and DihedralGroup")

    return {
        "elements": elts,
        "permutations": perms,
        "degree": d,
        "representation": "given",
        "side": None,
    }


def group_action_permutations(
    G: FiniteGroup,
    representation: str = "regular",
    side: str = "left",
    identity_first: bool = True,
) -> dict[str, Any]:
    if representation == "regular":
        return regular_action_permutations(G, side=side, identity_first=identity_first)
    if representation == "given":
        return given_action_permutations(G, identity_first=identity_first)
    raise ValueError("representation must be 'regular' or 'given'")


def regular_permutation_group(G: FiniteGroup, side: str = "left", return_data: bool = True):
    """Pure-Python counterpart of the old Sage regular_permutation_group()."""
    action = regular_action_permutations(G, side=side, identity_first=True)
    elts = action["elements"]
    perms = action["permutations"]
    gens = []
    gen_map = {}
    index = {g: i for i, g in enumerate(elts)}
    for gen in G.generators():
        if gen not in index:
            continue
        p = perms[index[gen]]
        gens.append(p)
        gen_map[gen] = p
    if not gens:
        gens = [Permutation(range(len(elts)))]
    P = PermutationGroup(gens, degree=len(elts))
    if P.order() != len(elts):
        raise ValueError(f"regular representation has order {P.order()} instead of {len(elts)}")
    if not return_data:
        return P
    return {
        "group": P,
        "elements": elts,
        "index": index,
        "perm_of_gen": gen_map,
        "degree": len(elts),
    }


